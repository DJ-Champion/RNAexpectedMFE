# Fit the candidate models in R/models.R by unweighted nls on individual
# sequences. The 0 kcal/mol cap is applied at prediction time only, so the
# fitted surface is smooth and identical to what downstream code evaluates.

fit_mfe_model <- function(name, data) {
  spec <- mfe_models[[name]]
  nls(spec$formula, data = data, start = spec$start,
      control = nls.control(maxiter = 200))
}

fit_all_models <- function(data) {
  map(set_names(names(mfe_models)), fit_mfe_model, data = data)
}

predict_capped <- function(fit, data) {
  pmin(unname(predict(fit, newdata = data)), 0)
}

coefficient_table <- function(fits) {
  imap_dfr(fits, function(fit, name) {
    p <- summary(fit)$parameters
    tibble(
      model     = name,
      parameter = rownames(p),
      estimate  = p[, "Estimate"],
      std_error = p[, "Std. Error"],
      conf_low  = estimate - qnorm(0.975) * std_error,
      conf_high = estimate + qnorm(0.975) * std_error,
      t_value   = p[, "t value"],
      p_value   = p[, "Pr(>|t|)"]
    )
  })
}

# Write the fitted coefficients into the package as plain, diffable R code.
write_coefficients_r <- function(fits, n_obs, path = "R/coefficients.R") {
  entries <- imap_chr(fits, function(fit, name) {
    cf <- coef(fit)
    paste0("  ", name, " = c(",
           paste0(names(cf), " = ", sprintf("%.10g", cf), collapse = ", "),
           ")")
  })
  lines <- c(
    "# Generated by analysis/01_fit_models.R -- do not edit by hand.",
    paste0("# Unweighted nls on all ", format(n_obs, big.mark = ","),
           " synthetic sequences in data-raw/ (fitted ", Sys.Date(), ")."),
    "",
    "mfe_coefficients <- list(",
    paste0(entries, collapse = ",\n"),
    ")"
  )
  writeLines(lines, path)
}
